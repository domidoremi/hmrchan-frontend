import { createPinia, disposePinia, setActivePinia } from 'pinia'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { useToastStore } from '../toast'

let pinia: ReturnType<typeof createPinia>
beforeEach(() => {
  vi.useFakeTimers()
  pinia = createPinia()
  setActivePinia(pinia)
})
afterEach(() => {
  disposePinia(pinia)
  vi.useRealTimers()
})
function displayed(duration = 1000) {
  const store = useToastStore()
  const id = store.info('A timed notification', duration)
  store.setVisibleToasts([id])
  return { store, id }
}

describe('toast reading time', () => {
  it('retains only the unconsumed display time after a long hover', () => {
    const { store, id } = displayed()
    vi.advanceTimersByTime(300)
    store.pauseTimer(id)
    vi.advanceTimersByTime(5000)
    store.resumeTimer(id)
    vi.advanceTimersByTime(699)
    expect(store.toasts.map((item) => item.id)).toContain(id)
    vi.advanceTimersByTime(1)
    expect(store.toasts).toHaveLength(0)
  })
  it('does not restart the lifetime after a late brief hover', () => {
    const { store, id } = displayed()
    vi.advanceTimersByTime(900)
    store.pauseTimer(id)
    vi.advanceTimersByTime(50)
    store.resumeTimer(id)
    vi.advanceTimersByTime(100)
    expect(store.toasts).toHaveLength(0)
  })
  it('counts overlapping pauses independently and ignores duplicate events', () => {
    const { store, id } = displayed()
    vi.advanceTimersByTime(250)
    store.pauseTimer(id, 'pointer')
    store.pauseTimer(id, 'pointer')
    store.pauseTimer(id, 'focus')
    store.resumeTimer(id, 'pointer')
    store.resumeTimer(id, 'pointer')
    vi.advanceTimersByTime(5000)
    expect(store.toasts).toHaveLength(1)
    store.resumeTimer(id, 'focus')
    vi.advanceTimersByTime(749)
    expect(store.toasts).toHaveLength(1)
    vi.advanceTimersByTime(1)
    expect(store.toasts).toHaveLength(0)
  })
  it('gives queued notifications their full lifetime once displayed', () => {
    const { store, id } = displayed()
    const second = store.info('Next', 1000)
    const third = store.info('Third', 1000)
    vi.advanceTimersByTime(1000)
    expect(store.toasts.map((item) => item.id)).toEqual([second, third])
    store.setVisibleToasts([second])
    vi.advanceTimersByTime(999)
    expect(store.toasts.map((item) => item.id)).toEqual([second, third])
    vi.advanceTimersByTime(1)
    expect(store.toasts.map((item) => item.id)).toEqual([third])
    expect(store.timings.has(id)).toBe(false)
  })
  it('does not consume time before the presenter mounts', () => {
    const store = useToastStore()
    const id = store.info('Waiting for renderer', 1000)
    vi.advanceTimersByTime(10000)
    expect(store.toasts).toHaveLength(1)
    store.setVisibleToasts([id])
    vi.advanceTimersByTime(1000)
    expect(store.toasts).toHaveLength(0)
  })
  it('pauses existing and newly queued messages while the document is hidden', () => {
    const { store, id } = displayed()
    vi.advanceTimersByTime(300)
    store.setPageHidden(true)
    const second = store.info('Added in background', 1000)
    vi.advanceTimersByTime(10000)
    expect(store.toasts).toHaveLength(2)
    store.setPageHidden(false)
    vi.advanceTimersByTime(700)
    expect(store.toasts.map((item) => item.id)).toEqual([second])
    store.setVisibleToasts([second])
    vi.advanceTimersByTime(1000)
    expect(store.toasts).toHaveLength(0)
    expect(store.timings.has(id)).toBe(false)
  })
  it('keeps window focus and document visibility as independent pause reasons', () => {
    const { store, id } = displayed()
    vi.advanceTimersByTime(250)
    store.setWindowFocused(false)
    store.setPageHidden(true)
    store.setPageHidden(false)
    vi.advanceTimersByTime(5000)
    expect(store.toasts).toHaveLength(1)
    const next = store.info('Added while away', 1000)
    store.removeToast(id)
    store.setVisibleToasts([next])
    vi.advanceTimersByTime(5000)
    expect(store.toasts).toHaveLength(1)
    store.setWindowFocused(true)
    vi.advanceTimersByTime(1000)
    expect(store.toasts).toHaveLength(0)
  })
  it('retains collapsed and running actions until their independent pauses end', () => {
    const { store, id } = displayed()
    store.pauseTimer(id, 'collapsed')
    store.pauseTimer(id, 'action')
    store.resumeTimer(id, 'collapsed')
    vi.advanceTimersByTime(3000)
    expect(store.toasts).toHaveLength(1)
    store.resumeTimer(id, 'action')
    vi.advanceTimersByTime(1000)
    expect(store.toasts).toHaveLength(0)
  })
  it('keeps errors until explicitly dismissed and honors an explicit duration', () => {
    const store = useToastStore()
    const id = store.error('Could not save')
    store.setVisibleToasts([id])
    vi.advanceTimersByTime(60000)
    expect(store.toasts).toHaveLength(1)
    store.removeToast(id)
    const timed = store.error('Brief error', 500)
    store.setVisibleToasts([timed])
    vi.advanceTimersByTime(500)
    expect(store.toasts).toHaveLength(0)
  })
  it('cleans active timers and pause state when cleared or disposed', () => {
    const { store, id } = displayed()
    store.pauseTimer(id)
    store.clear()
    store.resumeTimer(id)
    expect(store.timings.size).toBe(0)
    expect(vi.getTimerCount()).toBe(0)
    const next = store.info('After clear')
    store.setVisibleToasts([next])
    disposePinia(pinia)
    expect(vi.getTimerCount()).toBe(0)
  })
})
